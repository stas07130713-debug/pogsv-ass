  /* Плоский список без повторов — для режима свободной тренировки.
     Один и тот же вопрос встречается в нескольких билетах; здесь он один. */
  function unique() {
    var seen = {}, list = [];
    TICKETS.forEach(function (t) {
      t.questions.forEach(function (q) {
        var key = q.q.toLowerCase().replace(/[^0-9a-zа-яё]/g, '');
        if (seen[key]) return;
        seen[key] = true;
        list.push(q);
      });
    });
    return list;
  }

  var ALL = unique();

  VGSCH.data.vgk = {
    TOPICS: TOPICS,
    tickets: TICKETS,
    /** Все вопросы без повторов. */
    all: function () { return ALL; },
    /** Вопросы, у которых подтверждён верный вариант. */
    ready: function (topic) {
      return ALL.filter(function (q) {
        return q.correct !== null && (!topic || q.topic === topic);
      });
    },
    /** Темы с числом вопросов — для экрана выбора. */
    topics: function () {
      var by = {};
      ALL.forEach(function (q) {
        if (q.correct === null) return;
        by[q.topic] = (by[q.topic] || 0) + 1;
      });
      return Object.keys(by).map(function (k) {
        return { key: k, title: TOPICS[k] || k, count: by[k] };
      }).sort(function (a, b) { return b.count - a.count; });
    },
    ticket: function (no) {
      return TICKETS.filter(function (t) { return t.no === no; })[0] || null;
    }
  };
