/* Устав ВГСЧ — Приказ МЧС России от 09.06.2017 № 251, пункт 22.
 *
 * Дословно (п. 22):
 *   «При работе в горных выработках с непригодной для дыхания атмосферой в баллоне ДА
 *    со сжатым кислородом или кислородно-азотной смесью (далее — дыхательная смесь)
 *    должен резервироваться запас дыхательной смеси, соответствующий давлению 5 МПа (50 кг/см2).
 *    Рабочий запас дыхательной смеси в баллоне ДА, соответствующий давлению 15 МПа (150 кг/см2),
 *    следует расходовать исходя из расчета:
 *      при передвижении вверх, по горизонтальным горным выработкам или вниз по горным
 *      выработкам с углом наклона до 10° включительно — половину рабочего запаса на
 *      передвижение в направлении вперед и половину на возвращение;
 *      при передвижении по горным выработкам с углом наклона более 10° вниз — одну треть
 *      рабочего запаса на передвижение в направлении вперед и две трети — на возвращение.
 *    Если отделение передвигается по горным выработкам с непригодной для дыхания атмосферой
 *    с использованием механических транспортных средств, запас дыхательной смеси в баллоне ДА
 *    на обратный путь определяется из расчета возвращения пешком.»
 *
 * ЗАМЕНЯЕМЫЙ БЛОК ДАННЫХ.
 */
(function (VGSCH) {
  'use strict';

  var RESERVE_PRESSURE_MPA = 5;
  var WORKING_RESERVE_MPA = 15;

  /* Геометрическая категория участка. Границы заданы явно и не пересекаются:
   * ровно 10° вниз попадает в DOWN_TO_10 («до 10° включительно»),
   * 10,1° вниз — уже в DOWN_OVER_10. */
  var SLOPE_CATEGORY = {
    HORIZONTAL: 'horizontal',    // угол 0
    UP: 'up',                    // передвижение вверх, любой угол
    DOWN_TO_10: 'down_to_10',    // вниз, 0 < угол <= 10
    DOWN_OVER_10: 'down_over_10' // вниз, угол > 10
  };

  /* Правило распределения рабочего запаса. Это НЕ геометрия участка:
   * одно и то же правило ½–½ действует и на горизонтали, и на подъёме,
   * и на спуске до 10° включительно. */
  var ALLOCATION = {
    HALF_HALF: 'half_half',
    THIRD_TWO_THIRDS: 'third_two_thirds'
  };

  var ALLOCATION_TITLE = {
    half_half: 'передвижение вверх, по горизонтальной выработке или спуск с углом ' +
               'до 10° включительно — половина рабочего запаса вперёд',
    third_two_thirds: 'спуск с углом наклона более 10° — одна треть рабочего запаса вперёд'
  };

  /**
   * Категория участка по геометрии.
   * @param {number} slopeDeg  угол наклона выработки, градусы, >= 0
   * @param {string} incline   'горизонталь' | 'подъём' | 'спуск'
   */
  function slopeCategory(slopeDeg, incline) {
    if (typeof slopeDeg !== 'number' || !isFinite(slopeDeg) || slopeDeg < 0) {
      throw new Error('slopeDeg должен быть неотрицательным числом, получено: ' + slopeDeg);
    }
    if (incline === 'горизонталь' || slopeDeg === 0) return SLOPE_CATEGORY.HORIZONTAL;
    if (incline === 'подъём') return SLOPE_CATEGORY.UP;
    if (incline === 'спуск') {
      return slopeDeg <= 10 ? SLOPE_CATEGORY.DOWN_TO_10 : SLOPE_CATEGORY.DOWN_OVER_10;
    }
    throw new Error('Неизвестное направление участка: ' + incline);
  }

  /**
   * Доля рабочего запаса, отводимая на движение «туда», по п. 22.
   * Возвращает точную дробь, чтобы не терять точность до финального округления.
   * @returns {{forwardNum:number, forwardDen:number, backNum:number, backDen:number, rule:string}}
   */
  function forwardShare(category) {
    switch (category) {
      case SLOPE_CATEGORY.HORIZONTAL:
      case SLOPE_CATEGORY.UP:
      case SLOPE_CATEGORY.DOWN_TO_10:
      case ALLOCATION.HALF_HALF:
        return {
          forwardNum: 1, forwardDen: 2,
          backNum: 1, backDen: 2,
          rule: 'половина рабочего запаса вперёд, половина на возвращение'
        };
      case SLOPE_CATEGORY.DOWN_OVER_10:
      case ALLOCATION.THIRD_TWO_THIRDS:
        return {
          forwardNum: 1, forwardDen: 3,
          backNum: 2, backDen: 3,
          rule: 'одна треть рабочего запаса вперёд, две трети на возвращение'
        };
      default:
        throw new Error('Неизвестная категория уклона: ' + category);
    }
  }

  /**
   * Правило распределения для маршрута из нескольких участков.
   * Если хоть один участок «туда» — спуск более 10° вниз, на весь маршрут
   * распространяется более строгое правило 1/3–2/3.
   */
  function routeCategory(segments) {
    for (var i = 0; i < segments.length; i++) {
      var seg = segments[i];
      if (seg.direction !== 'туда') continue;
      if (slopeCategory(seg.slopeDeg, seg.incline) === SLOPE_CATEGORY.DOWN_OVER_10) {
        return ALLOCATION.THIRD_TWO_THIRDS;
      }
    }
    return ALLOCATION.HALF_HALF;
  }

  /** Человекочитаемое название правила распределения. */
  function allocationTitle(category) {
    if (ALLOCATION_TITLE[category]) return ALLOCATION_TITLE[category];
    return ALLOCATION_TITLE[category === SLOPE_CATEGORY.DOWN_OVER_10
      ? ALLOCATION.THIRD_TWO_THIRDS : ALLOCATION.HALF_HALF];
  }

  VGSCH.normative = VGSCH.normative || {};
  VGSCH.normative.ustav251 = {
    sourceId: 'ustav251',
    point: 'п. 22',

    RESERVE_PRESSURE_MPA: RESERVE_PRESSURE_MPA,
    WORKING_RESERVE_MPA: WORKING_RESERVE_MPA,
    SLOPE_CATEGORY: SLOPE_CATEGORY,
    ALLOCATION: ALLOCATION,

    slopeCategory: slopeCategory,
    forwardShare: forwardShare,
    routeCategory: routeCategory,
    allocationTitle: allocationTitle,

    /* При мехтранспорте запас на обратный путь считается из расчёта возвращения пешком. */
    mechTransportReturnOnFoot: true,

    quotes: {
      reserve: 'В баллоне ДА должен резервироваться запас дыхательной смеси, ' +
               'соответствующий давлению 5 МПа (50 кг/см²).',
      working: 'Рабочий запас дыхательной смеси в баллоне ДА, соответствующий давлению ' +
               '15 МПа (150 кг/см²), следует расходовать исходя из расчёта:',
      halfHalf: 'при передвижении вверх, по горизонтальным горным выработкам или вниз ' +
                'по горным выработкам с углом наклона до 10° включительно — половину ' +
                'рабочего запаса на передвижение в направлении вперёд и половину на возвращение;',
      thirdTwoThirds: 'при передвижении по горным выработкам с углом наклона более 10° вниз — ' +
                      'одну треть рабочего запаса на передвижение в направлении вперёд ' +
                      'и две трети — на возвращение.',
      mechTransport: 'Если отделение передвигается по горным выработкам с непригодной для ' +
                     'дыхания атмосферой с использованием механических транспортных средств, ' +
                     'запас дыхательной смеси в баллоне ДА на обратный путь определяется ' +
                     'из расчёта возвращения пешком.',
      returnPressure: 'п. 23. Перед включением в ДА командир отделения, с учётом минимального ' +
                      'показания манометров ДА в отделении, должен определить давление в баллоне ДА, ' +
                      'при котором прекращается работа или движение вперёд.',
      p38: 'п. 38. При входе в ЗВТ должна замеряться температура воздуха и рассчитываться допустимое ' +
           'время на передвижение или пребывание на месте в соответствии с Инструкцией. Время на ' +
           'передвижение должно распределяться следующим образом: одна треть — на передвижение ' +
           'в направлении вперёд и две трети — на возвращение. В дальнейшем замеры температуры ' +
           'воздуха и корректировка допустимого времени движения вперёд должна производиться через ' +
           'каждые 5 минут. При следовании вперёд механическим транспортом время на обратный путь ' +
           'должно определяться из расчёта возвращения пешком.',
      p39: 'п. 39. В случаях, когда отделение движется по горным выработкам с нарастающей температурой ' +
           'воздуха и возвращение его на ПБ предусмотрено тем же маршрутом, время фактического ' +
           'пребывания в ЗВТ определяется по максимальной температуре воздуха и исчисляется с момента ' +
           'входа отделения в горную выработку с непригодной для дыхания атмосферой.',
      p41: 'п. 41. Отделение должно прекратить выполнение задания в условиях ЗВТ, сообщить об этом ' +
           'на ПБ и выйти из зоны аварии на ПБ в случае если: температура воздуха нарастает на 3 °C ' +
           'и более за 5 минут; закончилось допустимое время пребывания или движения вперёд.',
      p43: 'п. 43. Работники ВГСЧ после нахождения в ЗВТ могут быть допущены к повторной работе в ЗВТ ' +
           'один раз в течение рабочей смены, при этом работникам ВГСЧ предоставляется отдых ' +
           'продолжительностью не менее двух часов. Отдых должен быть организован в горной выработке ' +
           'с пригодной для дыхания атмосферой и температурой воздуха не более 27 °C.',
      p44: 'п. 44. Запрещается повторное включение в ДА при выключении из него на время более 15 минут — ' +
           'при температуре воздуха от 0 °C до минус 5 °C, и более 5 минут — при температуре воздуха ' +
           'ниже минус 5 °C.'
    },

    /* П. 38: распределение допустимого ВРЕМЕНИ в ЗВТ и корректировка замерами каждые 5 минут. */
    ZVT_TIME_FORWARD_NUM: 1, ZVT_TIME_FORWARD_DEN: 3,
    ZVT_TIME_BACK_NUM: 2, ZVT_TIME_BACK_DEN: 3,
    ZVT_REMEASURE_INTERVAL_MIN: 5
  };
})(window.VGSCH = window.VGSCH || {});
