/* Теххарактеристики дыхательных аппаратов, состоящих на вооружении.
 *
 * ЗАПОЛНЯЕТСЯ ИЗ РУКОВОДСТВА ПО ЭКСПЛУАТАЦИИ (РЭ) КОНКРЕТНОГО АППАРАТА.
 * Ничего не подставлять «по памяти» и не переносить из старых учебников:
 * пока модель не описана здесь, задачи типа T11 (время защитного действия)
 * не генерируются — см. data/tasks/types.js, статус DISABLED.
 *
 * Шаблон записи:
 *   {
 *     id: 'р-30',                       // короткий идентификатор
 *     model: 'Р-30',                    // как в РЭ
 *     medium: 'сжатый кислород',        // 'сжатый кислород' | 'кислородно-азотная смесь'
 *                                       // | 'химически связанный кислород' | 'сжатый воздух'
 *     nominalPressureMPa: 20,           // номинальное давление в баллоне, МПа
 *     nominalProtectiveTimeMin: 240,    // номинальное время защитного действия, мин
 *     cylinderVolumeL: null,            // вместимость баллона, л
 *     source: 'РЭ Р-30, раздел 2, табл. 1',
 *     checkedOn: '2026-__-__'
 *   }
 *
 * ВАЖНО про аппараты на сжатом ВОЗДУХЕ (ДАСВ).
 * Устав ВГСЧ п. 22 задаёт резерв 5 МПа, рабочий запас 15 МПа и распределение
 * ½–½ / ⅓–⅔ только для ДА «со сжатым кислородом или кислородно-азотной смесью».
 * Правило прил. 6 п. 2 (рабочий объём — 75 %) сформулировано для сжатого
 * кислорода и для химически связанного кислорода. Для сжатого воздуха ни того,
 * ни другого правила в нормативной базе проекта нет: ФНП № 520 упоминает такие
 * аппараты только в прил. 6 п. 1 — для объектов открытых горных работ,
 * с номинальным ВЗД не менее одного часа.
 * Поэтому к ДАСВ применяется лишь общий предел прил. 6 п. 3 — не более четырёх
 * часов пребывания в непригодной для дыхания рудничной атмосфере. Доля 75 %
 * к нему НЕ применяется, пока не будет указан документ, который это
 * устанавливает.
 *
 * ЗАМЕНЯЕМЫЙ БЛОК ДАННЫХ.
 */
(function (VGSCH) {
  'use strict';

  var APPARATUS = [
    {
      id: 'р-30',
      model: 'Р-30',
      fullName: 'Респиратор изолирующий регенеративный на сжатом кислороде Р-30',
      medium: 'сжатый кислород',
      nominalPressureMPa: 20,          // разд. 3: «Давление в кислородном баллоне, МПа — 20»
      nominalProtectiveTimeMin: 240,   // прил. 1: «240 — номинальное время защитного действия
                                       // в минутах, при выполнении работы средней тяжести»
      cylinderVolumeL: null,           // в извлечённой таблице однозначно не читается — не подставляем
      lowPressureSignalMPa: 5.5,       // разд. 2: сигнал при снижении давления ниже 5,5 МПа
      workTempMinC: -20,               // разд. 2: от минус 20 °C до плюс 60 °C
      workTempMaxC: 60,
      source: 'РЭ Р30Р.00.000 РЭ1, ред. 22.03.2022: разд. 2, разд. 3, прил. 1',
      checkedOn: '2026-08-12'
    }
  ];

  /* ФНП № 520, прил. 6, п. 2 — доля номинала, принимаемая за рабочий объём. */
  var WORKING_VOLUME_SHARE = 0.75;

  /* ФНП № 520, прил. 6, п. 3 — предельная продолжительность пребывания в НДА. */
  var MAX_STAY_IN_UNBREATHABLE_MIN = 240;

  function byId(id) {
    for (var i = 0; i < APPARATUS.length; i++) {
      if (APPARATUS[i].id === id) return APPARATUS[i];
    }
    return null;
  }

  /** Есть ли вообще данные для генерации задач по аппаратам. */
  function isAvailable() {
    return APPARATUS.length > 0;
  }

  /* Среды, для которых прил. 6 п. 2 устанавливает долю 75 %. Для сжатого
     воздуха такого правила в нормативной базе проекта нет.

     ВНИМАНИЕ, ЗДЕСЬ ЕСТЬ ДОПУЩЕНИЕ. Пункт 2 формулирует долю по-разному:
       — для ДА на химически связанном кислороде — «объёму, который расходуется
         за 75 % номинального времени защитного действия», то есть прямо по времени;
       — для ДА на сжатом кислороде (КАС) — «75 % от объёма газо-дыхательной
         смеси в баллоне», то есть по объёму.
     Перевод доли объёма в долю времени верен только при равномерном расходе.
     Это допущение проговаривается пользователю в тексте решения задачи, чтобы
     оно не выдавалось за прямую норму. */
  var SHARE_APPLIES_TO = ['сжатый кислород', 'кислородно-азотная смесь', 'химически связанный кислород'];
  var SHARE_BY_VOLUME = ['сжатый кислород', 'кислородно-азотная смесь'];

  /**
   * Рабочее время защитного действия по прил. 6 п. 2 и ограничению п. 3.
   * @returns {{minutes:number, limitedBy:string, reason:string}}
   */
  function workingProtectiveTime(apparatusId) {
    var a = byId(apparatusId);
    if (!a) {
      throw new Error('Аппарат «' + apparatusId + '» отсутствует в data/normative/apparatus.js. ' +
                      'Задача не генерируется: характеристика не подтверждена руководством по эксплуатации.');
    }
    if (!(a.nominalProtectiveTimeMin > 0)) {
      throw new Error('Для аппарата «' + a.model + '» не указано номинальное время защитного действия.');
    }

    var shareApplies = SHARE_APPLIES_TO.indexOf(a.medium) !== -1;
    var t = shareApplies
      ? a.nominalProtectiveTimeMin * WORKING_VOLUME_SHARE
      : a.nominalProtectiveTimeMin;

    if (t > MAX_STAY_IN_UNBREATHABLE_MIN) {
      return {
        minutes: MAX_STAY_IN_UNBREATHABLE_MIN,
        limitedBy: 'прил. 6, п. 3',
        reason: (shareApplies
          ? 'Рабочее время (75 % номинального ВЗД) составляет ' + t + ' мин, однако максимальная '
          : 'Номинальное время защитного действия составляет ' + t + ' мин, однако максимальная ') +
          'продолжительность пребывания в непригодной для дыхания рудничной атмосфере ' +
          'с применением ДА не должна превышать четырёх часов.'
      };
    }
    if (!shareApplies) {
      return {
        minutes: t,
        limitedBy: 'прил. 6, п. 3',
        reason: 'Для среды «' + a.medium + '» доля 75 % (прил. 6, п. 2) нормативной базой проекта ' +
                'не установлена, поэтому применяется номинальное время защитного действия ' +
                a.model + ' — ' + t + ' мин — в пределах общего ограничения четырёх часов.'
      };
    }
    var byVolume = SHARE_BY_VOLUME.indexOf(a.medium) !== -1;
    return {
      minutes: t,
      limitedBy: 'прил. 6, п. 2',
      byVolume: byVolume,
      reason: byVolume
        ? 'Для ДА на сжатом кислороде рабочий объём принимается равным 75 % объёма ' +
          'газо-дыхательной смеси в баллоне. При равномерном расходе это соответствует ' +
          '75 % номинального времени защитного действия ' + a.model + ' (' +
          a.nominalProtectiveTimeMin + ' мин), то есть ' + t + ' мин.'
        : 'Объём, который расходуется за 75 % номинального времени защитного действия ' +
          a.model + ' (' + a.nominalProtectiveTimeMin + ' мин), — ' + t + ' мин.'
    };
  }

  VGSCH.normative = VGSCH.normative || {};
  VGSCH.normative.apparatus = {
    sourceId: 'fnp520',
    list: APPARATUS,
    WORKING_VOLUME_SHARE: WORKING_VOLUME_SHARE,
    MAX_STAY_IN_UNBREATHABLE_MIN: MAX_STAY_IN_UNBREATHABLE_MIN,
    byId: byId,
    isAvailable: isAvailable,
    workingProtectiveTime: workingProtectiveTime
  };
})(window.VGSCH = window.VGSCH || {});
